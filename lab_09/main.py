# Завдання 5: Зчитування 5 чисел від користувача та знаходження суми
user_numbers = []
for i in range(5):
    val = float(input(f"Введіть число {i + 1}: "))
    user_numbers.append(val)
print("Введені числа:", user_numbers)
print("Сума всіх чисел:", sum(user_numbers))
print("-" * 30)

# Завдання 6: Використання методів count() та index()
items = ["яблуко", "банан", "яблуко", "груша", "яблуко", "слива"]
target = "яблуко"
print("Список елементів:", items)
print(f"Кількість входжень '{target}':", items.count(target))
print(f"Перша позиція (індекс) '{target}':", items.index(target))