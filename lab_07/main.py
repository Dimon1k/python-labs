# Завдання 1: Перевірка рівності двох чисел
num1 = float(input("Введіть перше число: "))
num2 = float(input("Введіть друге число: "))
if num1 == num2:
    print("Числа рівні")
else:
    print("Числа не рівні")
print("-" * 30)

# Завдання 2: Перевірка, чи число більше нуля
num_check = float(input("Введіть число: "))
if num_check > 0:
    print("Число більше нуля")
else:
    print("Число менше або дорівнює нулю")
print("-" * 30)

# Завдання 3: Порівняння двох рядків
str1 = input("Введіть перший рядок: ")
