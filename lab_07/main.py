# Завдання 6: Перевірка трьох чисел на порядок зростання
a = float(input("Введіть перше число: "))
b = float(input("Введіть друге число: "))
c = float(input("Введіть третє число: "))

if a < b < c:
    print("Числа розташовані у порядку зростання")
else:
    print("Числа не розташовані у порядку зростання")