import math

# Завдання 1: Виведення повідомлення 3 способами (конкатенація, format, f-рядок)
name = "Олександр"
age = 18

print("Мене звати " + name + ", мені " + str(age) + " років.")
print("Мене звати {}, мені {} років.".format(name, age))
print(f"Мене звати {name}, мені {age} років.")
print("-" * 30)

# Завдання 2: Таблиця множення числа 7
for i in range(1, 11):
    print(f"7 x {i} = {7 * i}")
print("-" * 30)

# Завдання 3: Виведення числа Пі з різною точністю
pi_val = math.pi
print(f"2 знаки: {pi_val:.2f}")
print(f"3 знаки: {pi_val:.3f}")
print(f"5 знаків: {pi_val:.5f}")
print("-" * 30)

# Завдання 4: Числа та їх квадрати в 2 стовпці з вирівнюванням
for i in range(1, 11):
    print(f"{i:<5d} {i ** 2:<5d}")
print("-" * 30)

# Завдання 5: Таблиця покупок
print(f"{'Товар':<10} {'Кількість':<10} {'Ціна':<8}")
print(f"{'Яблука':<10} {5:<10d} {50.00:<8.2f}")
print(f"{'Молоко':<10} {2:<10d} {80.50:<8.2f}")
print(f"{'Хліб':<10} {1:<10d} {30.25:<8.2f}")