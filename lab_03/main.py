# Завдання 1: Вивести приклади всіх типів літералів
print(10)          # Ціле число (int)
print(3.14)        # Дробове число (float)
print("Текст")     # Рядок (str)
print(True)        # Логічне значення (bool)
print(None)        # Спеціальний літерал (None)
print("-" * 30)

# Завдання 2: Друк трьох рядків з різними видами лапок
print('Рядок в одинарних лапках')
print("Рядок у подвійних лапках")
print("""Багаторядковий
рядок у потрійних
лапках""")
print("-" * 30)

# Завдання 3: Сума, різниця та добуток двох числових літералів
num1 = 15
num2 = 4
print("Сума:", num1 + num2)
print("Різниця:", num1 - num2)
print("Добуток:", num1 * num2)
print("-" * 30)

# Завдання 4: Використання логічних літералів у виразах
print("True and False:", True and False)
print("True or False:", True or False)
print("-" * 30)

# Завдання 5: Список із трьох рядкових літералів
fruits = ["Яблуко", "Банан", "Апельсин"]
print("Список рядків:", fruits)
print("-" * 30)

